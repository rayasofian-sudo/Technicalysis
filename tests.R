# BDA400 Assignment 5 basic test file - run from the assignment folder
for (name in c("sma", "ema", "macd", "stdev", "linreg", "rsi", "stoch_rsi", "crossover", "crossunder")) {
  source(file.path("R_scripts", paste0(name, ".R")))
}
prices <- c(45, 50, 48, 55, 52, 49, 58, 60, 65, 62, 66, 63, 70, 68, 75, 72, 78, 74, 80, 77, 83, 79, 85)
stopifnot(isTRUE(all.equal(sma(c(10,12,15,20),3), c(37/3,47/3))))
stopifnot(isTRUE(all.equal(ema(c(10,12,15),3), c(10,11,13))))
m <- macd(prices, 3, 5, 2)
stopifnot(length(m$macd_line) == length(prices), length(m$signal_line) == length(prices))
stopifnot(isTRUE(all.equal(m$histogram, m$macd_line - m$signal_line)))
stopifnot(isTRUE(all.equal(stdev(c(2,4,4,4,5,5,7,9)), 2)))
lr <- linreg(c(2,4,6,8,10), 5, 0)
stopifnot(isTRUE(all.equal(lr$slope, 2)), isTRUE(all.equal(lr$intercept, 0)))
r <- rsi(prices, 5)
stopifnot(length(r) == length(prices), all(is.na(r[1:5])), all(r[6:length(r)] >= 0 & r[6:length(r)] <= 100))
s <- stoch_rsi(prices, 5, 3, 3)
stopifnot(length(s$k_line) > 0, length(s$d_line) > 0, all(s$k_line >= 0 & s$k_line <= 1))
a <- c(1,3,1,4); b <- c(2,2,2,2)
stopifnot(identical(crossover(a,b), c("None","Up","Down","Up")))
stopifnot(identical(crossunder(a,b), c("None","False","True","False")))
cat("All basic tests passed.\n")
cat("SMA:", sma(c(10,12,15,20),3), "\n")
cat("EMA:", ema(c(10,12,15),3), "\n")
cat("MACD final histogram:", tail(m$histogram,1), "\n")
cat("Standard deviation:", stdev(c(2,4,4,4,5,5,7,9)), "\n")
cat("Linear regression slope:", lr$slope, "\n")
cat("Last RSI:", tail(r,1), "\n")
cat("StochRSI final %%D:", tail(s$d_line,1), "\n")
cat("Crossover:", paste(crossover(a,b), collapse=", "), "\n")
cat("Crossunder:", paste(crossunder(a,b), collapse=", "), "\n")
